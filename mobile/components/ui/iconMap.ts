/** Filled Ionicons whose shape is painted in, so state (liked, bookmarked, rated) still shows. */
export const FILLED_SHAPES = new Set(['heart', 'star', 'bookmark', 'checkbox', 'ellipse', 'flag', 'location', 'notifications', 'trophy', 'medal']);

/** Ionicons name → base name and whether it is the filled variant ("heart" vs "heart-outline"). */
export function splitIoniconName(name: string): { base: string; outline: boolean; sharp: boolean } {
  if (name.endsWith('-outline')) return { base: name.slice(0, -'-outline'.length), outline: true, sharp: false };
  if (name.endsWith('-sharp')) return { base: name.slice(0, -'-sharp'.length), outline: false, sharp: true };
  return { base: name, outline: false, sharp: false };
}

/** All Sketchy drawings the app needs (input to the path generator, checked by a test). */
export function requiredSketchyNames(): string[] {
  return [...new Set([...Object.values(IONICON_TO_SKETCHY), ...EXTRA_SKETCHY])].sort();
}
