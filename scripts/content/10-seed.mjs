// Step 10 — supabase/seed.sql from content/trails.json: trails and checkpoints only, as idempotent
// upserts. No TRUNCATE, no users, completions, reviews or conditions. Photos are left out on purpose:
// they live in Storage and are published together with their trail_media rows by apply.mjs.
//
//   node scripts/content/10-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { lineEwkt, pointEwkt } from './lib/ewkt.mjs';
import { CONTENT, REPO, readJson } from './lib/paths.mjs';

const dataset = readJson(path.join(CONTENT, 'trails.json'));
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'NULL' : String(Number(v)));
const b = (v) => (v ? 'true' : 'false');

const lines = [
  '-- Trail catalogue seed for local development (supabase db reset).',
  `-- Generated by scripts/content/10-seed.mjs from content/trails.json (${dataset.generated_at}) — do not edit by hand.`,
  `-- ${dataset.counts.trails} trails, ${dataset.counts.checkpoints} checkpoints.`,
  '-- Safe to run more than once: rows are upserted by id. Nothing is deleted, and no users, completions,',
  '-- reviews or condition reports are created.',
  '-- Photos are not part of the seed: cover_image_url and trail_media point at files in the trail-media',
  '-- Storage bucket, which a seed cannot fill. Publish them (and the media rows) with',
  '--   SUPABASE_URL=… SUPABASE_SERVICE_ROLE_KEY=… node scripts/content/apply.mjs --apply',
  `-- ${dataset.attribution}`,
  '',
  'BEGIN;',
  '',
];

const trailCols = ['id', 'name_en', 'name_ka', 'description_en', 'description_ka', 'difficulty', 'region', 'distance_km', 'elevation_gain_m', 'estimated_hours', 'start_address', 'route', 'start_point', 'end_point', 'is_published'];
const trailUpdate = trailCols.filter((c) => c !== 'id' && c !== 'is_published').map((c) => `${c} = EXCLUDED.${c}`).join(', ');
const cpCols = ['id', 'trail_id', 'name_en', 'name_ka', 'description_en', 'description_ka', 'type', 'coordinates', 'elevation_m', 'sort_order', 'is_checkable'];
const cpUpdate = cpCols.filter((c) => c !== 'id').map((c) => `${c} = EXCLUDED.${c}`).join(', ');

for (const t of dataset.trails) {
  lines.push(`-- ${t.name_en}${t.osm_relation_id ? ` (OSM relation ${t.osm_relation_id})` : ''}`);
  lines.push(`INSERT INTO trails (${trailCols.join(', ')}) VALUES (`);
  lines.push(`  ${q(t.id)}, ${q(t.name_en)}, ${q(t.name_ka)},`);
  lines.push(`  ${q(t.description_en)},`);
  lines.push(`  ${q(t.description_ka)},`);
  lines.push(`  ${q(t.difficulty)}, ${q(t.region)}, ${n(t.distance_km)}, ${n(t.elevation_gain_m)}, ${n(t.estimated_hours)}, ${q(t.start_address)},`);
  lines.push(`  ${q(lineEwkt(t.route))},`);
  lines.push(`  ${q(pointEwkt(t.start_point))}, ${q(pointEwkt(t.end_point))}, true`);
  lines.push(`) ON CONFLICT (id) DO UPDATE SET ${trailUpdate};`);
  if (t.checkpoints.length) {
    lines.push(`INSERT INTO trail_checkpoints (${cpCols.join(', ')}) VALUES`);
    lines.push(
      t.checkpoints
        .map((c) => `  (${q(c.id)}, ${q(t.id)}, ${q(c.name_en)}, ${q(c.name_ka)}, ${q(c.description_en)}, ${q(c.description_ka)}, ${q(c.type)}, ${q(pointEwkt(c.coordinates))}, ${n(c.elevation_m)}, ${n(c.sort_order)}, ${b(c.is_checkable)})`)
        .join(',\n'),
    );
    lines.push(`ON CONFLICT (id) DO UPDATE SET ${cpUpdate};`);
  }
  lines.push('');
}
lines.push('COMMIT;', '');

const out = path.join(REPO, 'supabase', 'seed.sql');
fs.writeFileSync(out, lines.join('\n'));
console.log(`seed.sql: ${dataset.trails.length} trails, ${dataset.counts.checkpoints} checkpoints, ${(fs.statSync(out).size / 1048576).toFixed(2)} MB`);
